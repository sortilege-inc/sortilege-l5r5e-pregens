/* ============================================================
   sheet.js — renders one character sheet with an XP timeline.

   Reads window.L5R_CHARACTER, set by data/characters/<slug>.js — the one
   file the page stub loads (generated by scripts/build.py).

   Every tier is a full snapshot, so switching tiers is a re-render,
   not a diff-application. The changelog between adjacent tiers is
   computed here, at render time, from the two snapshots.
   ============================================================ */
(function () {
  "use strict";

  var RINGS = ["air", "earth", "fire", "water", "void"];

  // Rules text carries the corpus's symbol tokens; assets/symbols.js turns them
  // into glyphs and ring art. Degrade to the raw text if that file is absent.
  var syms = window.L5R_SYMBOLS || function (h) { return h || ""; };
  var RING_KANJI = { air: "風", earth: "土", fire: "火", water: "水", void: "空" };
  var SKILL_GROUP_LABEL = {
    artisan: "Artisan", martial: "Martial", scholar: "Scholar",
    social: "Social", trade: "Trade"
  };
  // which group each skill belongs to, for curriculum "Skill Group" lines
  var SKILL_GROUP_OF = {
    aesthetics: "artisan", composition: "artisan", design: "artisan", smithing: "artisan",
    fitness: "martial", melee: "martial", ranged: "martial", unarmed: "martial",
    meditation: "martial", tactics: "martial",
    culture: "scholar", government: "scholar", medicine: "scholar",
    sentiment: "scholar", theology: "scholar",
    command: "social", courtesy: "social", games: "social", performance: "social",
    commerce: "trade", labor: "trade", seafaring: "trade",
    skulduggery: "trade", survival: "trade"
  };
  var SKILL_LABEL = {
    aesthetics: "Aesthetics", composition: "Composition", design: "Design", smithing: "Smithing",
    fitness: "Fitness", melee: "Martial Arts [Melee]", ranged: "Martial Arts [Ranged]",
    unarmed: "Martial Arts [Unarmed]", meditation: "Meditation", tactics: "Tactics",
    culture: "Culture", government: "Government", medicine: "Medicine",
    sentiment: "Sentiment", theology: "Theology",
    command: "Command", courtesy: "Courtesy", games: "Games", performance: "Performance",
    commerce: "Commerce", labor: "Labor", seafaring: "Seafaring",
    skulduggery: "Skulduggery", survival: "Survival"
  };
  var BOOK_LABEL = {
    core_rulebook: "Core Rulebook", emerald_empire: "Emerald Empire",
    shadowlands: "Shadowlands", courts_of_stone: "Courts of Stone",
    court_of_stones: "Courts of Stone", path_of_waves: "Path of Waves",
    celestial_realms: "Celestial Realms", fields_of_victory: "Fields of Victory",
    mask_of_the_oni: "Mask of the Oni", writ_of_the_wanderer: "Writ of the Wanderer",
    wanderers: "Wanderer's Path", game_masters_kit: "Game Master's Kit",
    sins_of_regret: "Sins of Regret", blood_of_the_kami: "Blood of the Kami"
  };
  var CATEGORY_ORDER = [
    { key: "techniques", label: "Techniques", kanji: "技" },
    { key: "peculiarities", label: "Advantages & Disadvantages", kanji: "性" },
    { key: "titles", label: "Titles", kanji: "位" },
    { key: "signature_scrolls", label: "Title Abilities", kanji: "権" },
    { key: "bonds", label: "Bonds", kanji: "絆" },
    { key: "gear", label: "Equipment", kanji: "具" }
  ];

  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function el(id) { return document.getElementById(id); }
  function book(b) { return b ? (BOOK_LABEL[b] || b.replace(/_/g, " ")) : null; }
  function titleCase(s) {
    return String(s || "").replace(/(^|[\s\-])([a-z])/g, function (m, a, b) {
      return a + b.toUpperCase();
    });
  }
  function sourceLine(e) {
    if (!e.source || !e.source.book) return "";
    var b = book(e.source.book);
    return b + (e.source.page ? " · p. " + e.source.page : "");
  }

  // data/characters/<slug>.js sets this — one character per page, so a
  // 110-character archive never ships 110 characters' data to one reader.
  var CHAR = window.L5R_CHARACTER;

  function normName(s) {
    return String(s || "").normalize("NFKD").replace(/[\u0300-\u036f]/g, "")
      .toLowerCase().replace(/[^a-z0-9]+/g, "");
  }

  /* ---------------------------------------------------------- rendering */

  function renderRings(t) {
    return '<div class="rings">' + RINGS.map(function (r) {
      return '<div class="ring" data-ring="' + r + '">' +
        '<div class="rn">' + RING_KANJI[r] + " " + titleCase(r) + "</div>" +
        '<div class="rv">' + (t.rings[r] || 1) + "</div></div>";
    }).join("") + "</div>";
  }

  function renderDerived(t) {
    var d = t.derived || {};
    var s = t.social || {};
    var cells = [
      ["Endurance", d.endurance], ["Composure", d.composure],
      ["Focus", d.focus], ["Vigilance", d.vigilance], ["Void Points", d.void_points],
      ["Honor", s.honor], ["Glory", s.glory], ["Status", s.status]
    ];
    return '<div class="statrow">' + cells.map(function (c) {
      return '<div class="stat"><span class="k">' + esc(c[0]) + "</span>" +
        '<span class="v">' + (c[1] == null ? "—" : c[1]) + "</span></div>";
    }).join("") + "</div>";
  }

  function renderSkills(t) {
    var groups = Object.keys(t.skills || {});
    return '<div class="skillgrid">' + groups.map(function (g) {
      var skills = t.skills[g];
      var rows = Object.keys(skills).map(function (k) {
        var v = skills[k] || 0;
        var pips = "";
        for (var i = 1; i <= 5; i++) pips += '<span class="pip' + (i <= v ? " on" : "") + '"></span>';
        return '<div class="skill' + (v ? "" : " zero") + '">' +
          '<span class="sn">' + esc(SKILL_LABEL[k] || titleCase(k)) + "</span>" +
          '<span class="pips">' + pips + "</span>" +
          '<span class="sv">' + v + "</span></div>";
      }).join("");
      return '<div class="skillgroup"><h4>' + esc(SKILL_GROUP_LABEL[g] || titleCase(g)) +
        "</h4>" + rows + "</div>";
    }).join("") + "</div>";
  }

  function entryMechanics(e) {
    var bits = [];
    if (e.damage != null) bits.push("Damage " + e.damage);
    if (e.deadliness != null) bits.push("Deadliness " + e.deadliness);
    if (e.range) bits.push("Range " + e.range);
    if (e.armor) {
      if (e.armor.physical) bits.push("Physical " + e.armor.physical);
      if (e.armor.supernatural) bits.push("Supernatural " + e.armor.supernatural);
    }
    if (e.rarity) bits.push("Rarity " + e.rarity);
    if (e.zeni) bits.push("Cost " + e.zeni);
    if (e.xp_cost) bits.push(e.xp_cost + " XP");
    if (e.properties && e.properties.length) {
      bits.push(e.properties.map(function (p) { return p.name; }).join(", "));
    }
    return bits.length ? '<div class="mech"><span>' + bits.map(esc).join("</span><span>") +
      "</span></div>" : "";
  }

  function renderEntry(e, isNew) {
    var kind = e.kind ? titleCase(String(e.kind).replace(/_/g, " ")) : "";
    var badges = [];
    if (kind) badges.push('<span class="ek">' + esc(kind) + "</span>");
    if (e.rank) badges.push('<span class="ek">Rank ' + esc(e.rank) + "</span>");
    if (e.ring) badges.push('<span class="ek">' + esc(titleCase(e.ring)) + "</span>");
    if (e.types) badges.push('<span class="ek">' + esc(e.types) + "</span>");
    if (e.quantity > 1) badges.push('<span class="ek">×' + e.quantity + "</span>");
    if (e.custom) badges.push('<span class="ek custom">Custom</span>');
    var src = sourceLine(e);
    return '<details class="entry' + (isNew ? " new" : "") + '">' +
      "<summary>" + '<span class="en">' + esc(e.name) + "</span>" + badges.join("") + "</summary>" +
      '<div class="body">' + (syms(e.description) || '<p class="muted">No text recorded.</p>') +
      entryMechanics(e) +
      (src ? '<div class="src">' + esc(src) + "</div>" : "") +
      "</div></details>";
  }

  function renderCategory(t, prev, cat) {
    var list = t[cat.key] || [];
    if (!list.length) return "";
    var before = {};
    (prev ? prev[cat.key] || [] : []).forEach(function (e) { before[e.name] = true; });
    var sorted = list.slice().sort(function (a, b) {
      return (a.kind || "").localeCompare(b.kind || "") || a.name.localeCompare(b.name);
    });
    return '<section><h2 class="section-h"><span class="kanji">' + cat.kanji + "</span>" +
      esc(cat.label) + '<span class="en">' + list.length + " entries</span></h2>" +
      '<div class="entries">' +
      sorted.map(function (e) { return renderEntry(e, prev && !before[e.name]); }).join("") +
      "</div></section>";
  }

  // Concept material that became part of the record on promotion. Raw prose,
  // meant to be edited into something narrative later, so it is rendered as
  // paragraphs rather than dressed up.
  /* A bio is the character's concept notes, landed by scripts/promote.py, and
     those are written in Markdown — headings, bold, bullet lists, horizontal
     rules. Rendering them as plain text put literal "**Ujik Diviner**" and
     "### Cards" on the page, so this handles the small subset the concepts
     actually use. Escaping happens first and the formatting is applied to the
     escaped text, so nothing in a note can inject markup. */
  function bioInline(t) {
    return t
      .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
      .replace(/(^|[\s(])\*([^*\n]+)\*(?=[\s.,;:)]|$)/g, "$1<em>$2</em>")
      .replace(/`([^`]+)`/g, "<code>$1</code>");
  }

  function renderBio(bio) {
    if (!bio || !String(bio).trim()) return "";
    /* Line by line rather than block by block: the concepts put a heading and
       the list under it in one run of lines with no blank between, so
       classifying whole blank-line-separated blocks left "### Cards" and its
       bullets stranded together in a single paragraph. */
    var out = [], para = [], list = [];
    function flushPara() {
      if (!para.length) return;
      out.push("<p>" + bioInline(esc(para.join("\n"))).replace(/\n/g, "<br>") + "</p>");
      para = [];
    }
    function flushList() {
      if (!list.length) return;
      out.push("<ul>" + list.map(function (i) {
        return "<li>" + bioInline(esc(i)) + "</li>";
      }).join("") + "</ul>");
      list = [];
    }
    String(bio).split("\n").forEach(function (line) {
      var t = line.trim();
      if (!t) { flushList(); flushPara(); return; }
      if (/^-{3,}$/.test(t)) { flushList(); flushPara(); out.push("<hr>"); return; }
      var h = t.match(/^(#{1,6})\s+(.*)$/);
      if (h) {
        flushList(); flushPara();
        // the notes' headings sit inside the Bio section, a level below it
        out.push("<h" + Math.min(6, h[1].length + 2) + ">" + bioInline(esc(h[2])) +
                 "</h" + Math.min(6, h[1].length + 2) + ">");
        return;
      }
      var li = t.match(/^[-*+]\s+(.*)$/);
      if (li) { flushPara(); list.push(li[1]); return; }
      flushList();
      para.push(t);
    });
    flushList(); flushPara();
    return '<section><h2 class="section-h"><span class="kanji">伝</span>Bio' +
      '<span class="en">From the concept notes</span></h2>' +
      '<div class="bio-body">' + out.join("") + "</div></section>";
  }

  function renderDutyDesire(t) {
    var s = t.social || {};
    if (!s.giri && !s.ninjo) return "";
    var tenets = s.bushido_tenets || {};
    return '<section><h2 class="section-h"><span class="kanji">義 · 仁情</span>Duty &amp; Desire' +
      '<span class="en">Giri · Ninjō</span></h2><div class="duty-desire">' +
      (s.giri ? '<div class="gn-card giri"><div class="gn-label">Giri<span class="en">Duty</span></div>' +
        "<p>" + esc(s.giri) + "</p></div>" : "") +
      (s.ninjo ? '<div class="gn-card ninjo"><div class="gn-label">Ninjō<span class="en">Desire</span></div>' +
        "<p>" + esc(s.ninjo) + "</p></div>" : "") +
      "</div>" +
      (tenets.paramount ? '<p class="small muted" style="margin-top:0.8rem">Paramount tenet <strong>' +
        esc(tenets.paramount) + "</strong>" +
        (tenets.less_significant ? " · Less significant <strong>" +
          esc(tenets.less_significant) + "</strong>" : "") + "</p>" : "") +
      "</section>";
  }

  /* ---------------------------------------------------------- curriculum */

  // The school's own advancement table, straight from the compendium's
  // curriculum journal. Entries the character has actually taken are ticked,
  // so it reads as "what this school offers, and what they took of it".
  function renderCurriculum(t) {
    var cur = CHAR.curriculum || [];
    if (!cur.length) return "";

    var have = {};
    (t.techniques || []).forEach(function (e) { have[normName(e.name)] = true; });
    var skills = {};
    Object.keys(t.skills || {}).forEach(function (g) {
      Object.keys(t.skills[g]).forEach(function (k) {
        if (t.skills[g][k]) skills[normName(SKILL_LABEL[k] || k)] = true;
      });
    });

    var byRank = {};
    cur.forEach(function (e) { (byRank[e.rank] = byRank[e.rank] || []).push(e); });

    var rows = Object.keys(byRank).sort(function (a, b) { return a - b; }).map(function (r) {
      var reached = t.rank && Number(r) <= t.rank;
      var cells = byRank[r].map(function (e) {
        var taken = e.kind === "Technique" ? have[normName(e.label)]
          : e.kind === "Skill" ? skills[normName(e.label)] : false;
        return '<span class="cur-entry' + (taken ? " taken" : "") + '">' +
          (e.group ? '<em>(' + esc(e.group) + ")</em> " : "") + esc(e.label) +
          (e.prereq ? ' <span class="muted small">prereq</span>' : "") +
          '<span class="cur-kind">' + esc(e.kind) + "</span></span>";
      }).join("");
      return '<tr class="' + (Number(r) === t.rank ? "cur-current" : reached ? "cur-past" : "") +
        '"><td class="cur-rank">' + r + "</td><td>" + cells + "</td></tr>";
    }).join("");

    return '<section><h2 class="section-h"><span class="kanji">修</span>School Curriculum' +
      '<span class="en">' + esc(t.school || CHAR.school || "") + "</span></h2>" +
      '<p class="muted small">Ticked entries are ones this character has taken at this tier.</p>' +
      '<div class="cur-wrap"><table class="cur-table"><tbody>' + rows +
      "</tbody></table></div>" +
      titleCurriculumSection(t) +
      "</section>";
  }

  /* ------------------------------------------------- twenty questions */

  // Question wording and page references come from the l5r5e system's own
  // en.json (data/twenty_questions.js) — never retyped here.
  var Q = window.L5R_20Q || {};

  function fieldLabel(f) {
    return (Q.fields || {})[f] || titleCase(f.replace(/_/g, " "));
  }

  // Answers store raw keys ("meditation", "fire"); show them the way the rest
  // of the sheet does.
  var RING_SET = { air: 1, earth: 1, fire: 1, water: 1, "void": 1 };
  function prettyValue(f, v) {
    if (typeof v !== "string") return String(v);
    if (RING_SET[v]) return titleCase(v) + " Ring";
    if (SKILL_LABEL[v]) return SKILL_LABEL[v];
    return v;
  }

  function renderQuestions() {
    var tq = CHAR.twenty_questions || {};
    var steps = tq.steps || {};
    if (!Object.keys(steps).length) {
      return '<p class="lede">No twenty questions recorded for ' + esc(CHAR.name) +
        ".</p>";
    }
    var pow = tq.template === "pow";
    var html = '<p class="muted small">' +
      "The Game of Twenty Questions as answered at this character's making. " +
      "Question wording and page references are the system's own." + "</p>";

    (Q.parts || []).forEach(function (part) {
      var rows = part.questions.map(function (n) {
        var step = steps["step" + n];
        if (!step) return "";
        var text = ((Q.questions || {})[n] || {})[pow ? "pow" : "core"] ||
          ((Q.questions || {})[n] || {}).core || ("Question " + n);
        // the question number is already at the head of the official string
        var body = [];
        Object.keys(step.answers || {}).forEach(function (f) {
          body.push('<div class="qa-row"><dt>' + esc(fieldLabel(f)) + "</dt><dd>" +
            esc(prettyValue(f, step.answers[f])) + "</dd></div>");
        });
        Object.keys(step.picks || {}).forEach(function (f) {
          body.push('<div class="qa-row"><dt>' + esc(fieldLabel(f)) + "</dt><dd>" +
            step.picks[f].map(function (n2) {
              return '<span class="chip">' + esc(n2) + "</span>";
            }).join(" ") + "</dd></div>");
        });
        return '<div class="qa"><h3 class="qa-q">' + esc(text) + "</h3>" +
          '<dl class="qa-body">' + body.join("") + "</dl></div>";
      }).join("");
      if (!rows.replace(/\s/g, "")) return;
      html += '<h2 class="section-h"><span class="kanji">問</span>' +
        esc((pow && part.title_pow) || part.title) + "</h2>" + rows;
    });
    return html;
  }

  /* ------------------------------------------------- title curriculum */

  // A title carries its own curriculum, and its purchases are recorded against
  // it (the `via` field), so what was actually taken toward it can be ticked
  // the same way the school's curriculum is.
  function renderTitleCurricula(t) {
    var held = t.titles || [];
    if (!held.length) return "";
    var all = CHAR.title_curricula || {};

    return held.map(function (title) {
      var cur = all[normName(title.name)];

      // what this character bought toward this title
      var viaTech = {}, viaSkill = {}, viaGroup = {}, viaKind = {};
      var viaMartial = false, bought = [];
      (t.techniques || []).concat(t.signature_scrolls || []).forEach(function (e) {
        if (e.via && normName(e.via) === normName(title.name)) {
          viaTech[normName(e.name)] = true;
          if (e.kind) viaKind[normName(e.kind)] = true;
          bought.push(e.name);
        }
      });
      (t.advancements || []).forEach(function (a) {
        if (a.via && normName(a.via) === normName(title.name)) {
          if (a.skill) {
            viaSkill[normName(SKILL_LABEL[a.skill] || a.skill)] = true;
            var grp = SKILL_GROUP_OF[a.skill];
            if (grp) viaGroup[grp] = true;
            if (grp === "martial" && /^(melee|ranged|unarmed)$/.test(a.skill)) {
              viaMartial = true;
            }
          }
          bought.push(a.label);
        }
      });

      var spent = title.xp_used, cost = title.xp_cost;
      // "Active" is the title still being worked through. A completed title is
      // done, not current — the same reading the school curriculum uses, where
      // cur-current is the rank you are at and cur-past is one you finished.
      var complete = cost != null && spent != null && spent >= cost;
      var active = cost != null && spent != null && spent < cost;
      var head = '<h3 class="cur-title' + (active ? " active" : "") + '">' +
        esc(title.name) +
        (spent != null && cost
          ? ' <span class="cur-prog' + (complete ? " done" : " active") + '">' +
            spent + " / " + cost + " XP · " + (complete ? "complete" : "active") +
            "</span>"
          : "") + "</h3>";

      var meta = [];
      // a campaign-renamed title says whose curriculum it is actually using
      if (cur && cur.aliased_from) {
        meta.push("Curriculum: <strong>" + esc(cur.aliased_from) + "</strong>");
      }
      if (cur && cur.ability) meta.push("Title ability: <strong>" + esc(cur.ability) + "</strong>");
      if (cur && cur.status_award) meta.push("Status award " + esc(cur.status_award));
      var metaHtml = meta.length
        ? '<p class="muted small cur-meta">' + meta.join(" &middot; ") + "</p>" : "";

      if (!cur) {
        // a campaign title with no compendium entry - show what was taken for it
        return head + metaHtml +
          '<p class="muted small">No compendium curriculum for this title; it is ' +
          "campaign-specific. Taken toward it:</p>" +
          (bought.length
            ? '<div class="cur-wrap"><table class="cur-table"><tbody><tr>' +
              '<td class="cur-rank">&mdash;</td><td>' +
              bought.map(function (n) {
                return '<span class="cur-entry taken">' + esc(n) + "</span>";
              }).join("") + "</td></tr></tbody></table></div>"
            : '<p class="muted small">Nothing yet.</p>');
      }

      // "Trade Skills" is satisfied by raising any trade skill; "Martial Arts
      // [Choose One]" by raising any of the three martial arts.
      function entryTaken(e) {
        if (e.kind === "Technique") return !!viaTech[normName(e.label)];
        if (e.kind === "Skill Group") {
          var g = normName(e.label).replace(/skills?$/, "");
          return !!viaGroup[g];
        }
        if (e.kind === "Skill") {
          if (/chooseone/.test(normName(e.label))) return viaMartial;
          return !!viaSkill[normName(e.label)];
        }
        // "(kata) Rank 1-2 Kata" is satisfied by taking a kata for this title
        if (e.kind === "Tech. Grp.") return !!(e.group && viaKind[normName(e.group)]);
        return false;
      }

      var cells = cur.entries.map(function (e) {
        var taken = entryTaken(e);
        return '<span class="cur-entry' + (taken ? " taken" : "") + '">' +
          (e.group ? '<em>(' + esc(e.group) + ")</em> " : "") + esc(e.label) +
          (e.prereq ? ' <span class="muted small">prereq</span>' : "") +
          '<span class="cur-kind">' + esc(e.kind) + "</span></span>";
      }).join("");

      // Purchases toward the title that are not already a ticked curriculum
      // line. "Performance +1 (0 -> 1)" satisfies the "Performance" line, so
      // strip the "+1 (a -> b)" tail before comparing.
      function advStem(n) {
        return normName(String(n).replace(/\s*\+\d+\s*\(.*\)\s*$/, ""));
      }
      var extra = bought.filter(function (n) {
        return !cur.entries.some(function (e) {
          return entryTaken(e) && (normName(e.label) === advStem(n) ||
                                   normName(e.label) === normName(n));
        });
      });

      return head + metaHtml +
        '<div class="cur-wrap"><table class="cur-table"><tbody>' +
        '<tr class="' + (active ? "cur-current" : complete ? "cur-past" : "") + '">' +
        '<td class="cur-rank">\u4f4d</td><td>' + cells + "</td></tr>" +
        (extra.length
          ? '<tr><td class="cur-rank">+</td><td>' + extra.map(function (n) {
              return '<span class="cur-entry taken">' + esc(n) + "</span>";
            }).join("") + "</td></tr>"
          : "") +
        "</tbody></table></div>";
    }).join("");
  }

  function titleCurriculumSection(t) {
    var html = renderTitleCurricula(t);
    if (!html) return "";
    var n = (t.titles || []).length;
    return '<h2 class="section-h" style="margin-top:2.2rem">' +
      '<span class="kanji">\u4f4d</span>Title Curriculum' +
      '<span class="en">' + n + (n === 1 ? " title held" : " titles held") +
      "</span></h2>" + html;
  }

  /* ---------------------------------------------------------- changelog */

  function names(list) {
    var m = {};
    (list || []).forEach(function (e) { m[e.name] = e; });
    return m;
  }

  function renderChangelog(idx) {
    if (idx === 0) return "";
    var t = CHAR.tiers[idx], p = CHAR.tiers[idx - 1];
    var lines = [];

    RINGS.forEach(function (r) {
      var a = p.rings[r] || 1, b = t.rings[r] || 1;
      if (b !== a) lines.push(['<span class="gain">', titleCase(r) + " Ring " + a + " → " + b]);
    });
    Object.keys(t.skills || {}).forEach(function (g) {
      Object.keys(t.skills[g]).forEach(function (k) {
        var a = (p.skills[g] || {})[k] || 0, b = t.skills[g][k] || 0;
        if (b !== a) {
          lines.push([b > a ? '<span class="gain">' : '<span class="lose">',
            (SKILL_LABEL[k] || titleCase(k)) + " " + a + " → " + b]);
        }
      });
    });
    CATEGORY_ORDER.forEach(function (cat) {
      var before = names(p[cat.key]), after = names(t[cat.key]);
      Object.keys(after).forEach(function (n) {
        if (!before[n]) lines.push(['<span class="gain">', n]);
      });
      Object.keys(before).forEach(function (n) {
        if (!after[n] && cat.key !== "gear") lines.push(['<span class="lose">', n]);
      });
    });
    if (t.rank !== p.rank) {
      lines.unshift(['<span class="gain">', "School Rank " + p.rank + " → " + t.rank]);
    }
    if (!lines.length) return "";

    return '<div class="changelog"><h4>Since ' + p.xp + " XP · " + (t.xp - p.xp) +
      " XP spent</h4><ul>" +
      lines.map(function (l) { return "<li>" + l[0] + esc(l[1]) + "</span></li>"; }).join("") +
      "</ul></div>";
  }

  /* ---------------------------------------------------------- timeline */

  // "Gunsō, Rank 4" -> "Gunsō"; "Rank 2" alone -> nothing (it is not a title)
  function tierTitleOnly(t) {
    if (!t.label) return null;
    var head = t.label.split(",")[0].trim();
    return /^rank\b/i.test(head) ? null : head;
  }

  function tierTitle(t) {
    return tierTitleOnly(t) || t.school || CHAR.school || "—";
  }

  function renderTimeline() {
    return CHAR.tiers.map(function (t, i) {
      return '<button class="tl-node' + (i === 0 ? " active" : "") +
        '" type="button" data-i="' + i + '">' +
        '<span class="tl-dot" aria-hidden="true"></span>' +
        '<span class="tl-top">' + esc(tierTitle(t)) + "</span>" +
        '<span class="tl-bot">' + t.xp + " XP" + (t.rank ? " · Rank " + t.rank : "") +
        "</span></button>";
    }).join("");
  }

  /* ---------------------------------------------------------- driver */

  function activate(idx) {
    var t = CHAR.tiers[idx];
    var prev = idx > 0 ? CHAR.tiers[idx - 1] : null;

    var titleOnly = tierTitleOnly(t);
    el("school-line").innerHTML = esc(t.school || CHAR.school || "") +
      (t.rank ? ' <span class="muted">· Rank ' + t.rank + "</span>" : "") +
      (titleOnly ? ' · <strong>' + esc(titleOnly) + "</strong>" : "");

    el("changelog-target").innerHTML = renderChangelog(idx);
    el("stats-target").innerHTML = renderRings(t) + renderDerived(t);
    el("duty-target").innerHTML = renderBio(CHAR.bio) + renderDutyDesire(t);
    el("skills-target").innerHTML =
      '<h2 class="section-h"><span class="kanji">技能</span>Skills' +
      '<span class="en">Ring + Skill</span></h2>' + renderSkills(t);
    el("content-target").innerHTML = CATEGORY_ORDER.map(function (c) {
      return renderCategory(t, prev, c);
    }).join("") + renderCurriculum(t);

    Array.prototype.forEach.call(document.querySelectorAll("#timeline .tl-node"), function (n, i) {
      n.classList.toggle("active", i === idx);
      if (i === idx && n.scrollIntoView) {
        n.scrollIntoView({ block: "nearest", inline: "center" });
      }
    });

    // the Play tab always shows the tier the timeline is on
    var frame = el("play-frame");
    var src = "../play/" + CHAR.slug + "-" + t.xp + "xp.html";
    if (frame.getAttribute("data-src") !== src) {
      frame.setAttribute("data-src", src);
      if (!el("panel-play").hidden) frame.src = src;
    }
    el("play-note").innerHTML = "Playing <strong>" + esc(CHAR.name) + "</strong> at " +
      t.xp + " XP" + (t.rank ? ", school rank " + t.rank : "") +
      '. Trackers, rolls and the log are saved in this browser, per tier. ' +
      '<a href="' + esc(src) + '" target="_blank" rel="noopener">Open full screen</a>.';
    renderActions(t);
    if (history.replaceState) {
      history.replaceState(null, "", "#" + t.xp + "xp");
    }
  }

  /* Play and Advance, under the chips.

     Both were reachable already and neither looked like an option: Play was a
     tab two thirds of the way across a tab bar, and advancing meant opening
     the Creator, finding the character in the drafts panel and pressing a +XP
     button on its row. These are the two things anyone does with a character
     who is already made, so they sit with its name.

     Play follows the timeline — the sheet you open is the tier you are looking
     at. Advance always starts from the character's highest tier, because that
     is where they actually are, so it says which that is rather than implying
     it advances from the tier on screen. */
  function renderActions(t) {
    var top = CHAR.tiers[CHAR.tiers.length - 1];
    var sheet = "../play/" + CHAR.slug + "-" + t.xp + "xp.html";
    var advance = "../creator/index.html?advance=" +
      encodeURIComponent(CHAR.slug);
    el("char-actions").innerHTML =
      '<a class="btn action-play" href="' + esc(sheet) + '">Play' +
        '<span class="act-note">' + t.xp + " XP sheet</span></a>" +
      '<a class="btn action-advance" href="' + esc(advance) + '">Advance' +
        '<span class="act-note">spend XP from ' + top.xp + "</span></a>";
  }

  function init() {
    if (!CHAR) {
      document.body.innerHTML = '<div class="wrap"><p class="lede">No character data ' +
        "loaded. Run <code>python3 scripts/build.py</code>.</p></div>";
      return;
    }
    document.title = CHAR.name + " — Sortilege L5R Pregens";
    el("char-name").textContent = CHAR.name;
    el("char-chips").innerHTML =
      (CHAR.clan ? '<span class="chip clan" data-clan="' + esc(CHAR.clan) + '">' +
        esc(CHAR.clan) + "</span>" : "") +
      (CHAR.family ? '<span class="chip">' + esc(CHAR.family) + " family</span>" : "") +
      (CHAR.role ? '<span class="chip">' + esc(CHAR.role) + "</span>" : "") +
      (CHAR.campaign ? '<span class="chip crimson">' + esc(CHAR.campaign) + "</span>" : "") +
      '<span class="chip">' + CHAR.tier_count +
        (CHAR.tier_count === 1 ? " XP tier" : " XP tiers") + "</span>";

    var p = el("portrait-target");
    p.innerHTML = CHAR.portrait
      ? '<img src="../' + esc(CHAR.portrait) + '" alt="' + esc(CHAR.name) + '">'
      : '<div class="placeholder">' + esc(CHAR.name.charAt(0)) + "</div>";

    el("timeline").innerHTML = renderTimeline();
    Array.prototype.forEach.call(document.querySelectorAll("#timeline .tl-node"), function (n) {
      n.addEventListener("click", function () { activate(Number(n.getAttribute("data-i"))); });
    });

    el("panel-questions").innerHTML = renderQuestions();

    Array.prototype.forEach.call(document.querySelectorAll("#tabbar button"), function (b) {
      b.addEventListener("click", function () {
        var tab = b.getAttribute("data-tab");
        Array.prototype.forEach.call(document.querySelectorAll("#tabbar button"),
          function (o) { o.classList.toggle("active", o === b); });
        ["dossier", "questions", "play"].forEach(function (t) {
          el("panel-" + t).hidden = t !== tab;
        });
        // the play sheet is only loaded once its tab is actually opened
        var frame = el("play-frame");
        if (tab === "play" && frame.getAttribute("data-src") &&
            frame.src.indexOf(frame.getAttribute("data-src")) < 0) {
          frame.src = frame.getAttribute("data-src");
        }
      });
    });

    // deep link: #57xp
    var m = /^#(\d+)xp$/.exec(location.hash);
    var start = 0;
    if (m) {
      CHAR.tiers.forEach(function (t, i) { if (t.xp === Number(m[1])) start = i; });
    }
    activate(start);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
